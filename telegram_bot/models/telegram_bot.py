import hashlib
import logging
import re
import secrets

from odoo import api, fields, models
from odoo.exceptions import UserError, ValidationError

from ..tools import TelegramClient

_logger = logging.getLogger(__name__)

# Update types the bot receives; anything else is not handled by the controller.
_ALLOWED_UPDATES = ["message", "callback_query"]


class TelegramBot(models.Model):
    """Telegram bot configuration and Bot API interaction."""

    _name = "telegram.bot"
    _description = "Telegram Bot"

    name = fields.Char(
        required=True,
    )
    bot_token = fields.Char(
        copy=False,
        groups="base.group_system",
        help="Token given by BotFather, in the form <bot id>:<secret>.",
    )
    webhook_secret = fields.Char(
        copy=False,
        groups="base.group_system",
        help="Telegram sends it in the X-Telegram-Bot-Api-Secret-Token header of "
        "every update; an update without it is ignored. Generated by "
        "'Register webhook' when empty (1-256 characters: A-Z, a-z, 0-9, _, -).",
    )
    chat_ids = fields.One2many(
        comodel_name="telegram.chat",
        inverse_name="bot_id",
    )
    command_ids = fields.Many2many(
        comodel_name="telegram.command",
        help="Additional commands that this bot should respond to.",
    )
    token_hash = fields.Char(
        compute="_compute_token_hash",
        store=True,
        index=True,
        copy=False,
        help="SHA256 hash of the bot token, to find the bot from the webhook URL.",
    )

    _token_hash_uniq = models.Constraint(
        "UNIQUE (token_hash)",
        "Another bot already uses this token!",
    )

    @staticmethod
    def _hash_token(token):
        """Return the SHA256 hex digest of a bot token, used for indexed lookup.

        :param str token: the bot token to hash
        :rtype: str
        """
        return hashlib.sha256(token.encode()).hexdigest()

    @api.depends("bot_token")
    def _compute_token_hash(self):
        for bot in self:
            bot.token_hash = bot.bot_token and self._hash_token(bot.bot_token)

    @api.model
    def find_by_token(self, token):
        """Find a bot by token using an indexed hash lookup.

        :param str token: the bot token from the webhook URL
        :return: matching ``telegram.bot`` record (sudo) or an empty recordset
        """
        if not token:
            return self.browse()
        return self.sudo().search(
            [("token_hash", "=", self._hash_token(token))], limit=1
        )

    @api.constrains("bot_token")
    def _check_bot_token_format(self):
        """Validate the bot token format: ``<bot id>:<secret>``.

        :raises ValidationError: if the token is malformed
        """
        for record in self.sudo():
            if record.bot_token and not re.fullmatch(
                r"\d+:[A-Za-z0-9_-]+", record.bot_token
            ):
                raise ValidationError(
                    self.env._(
                        "The bot token must have the form <bot id>:<secret>, "
                        "e.g. 123456789:AAHdqTcvCH1vGWJxfSeofSAs0K5PALDsaw"
                    )
                )

    @api.constrains("webhook_secret")
    def _check_webhook_secret_format(self):
        """Validate the webhook secret per the Telegram API (setWebhook).

        :raises ValidationError: if the secret is not 1-256 chars of ``A-Za-z0-9_-``
        """
        for record in self.sudo():
            if record.webhook_secret and not re.fullmatch(
                r"[A-Za-z0-9_-]{1,256}", record.webhook_secret
            ):
                raise ValidationError(
                    self.env._(
                        "The webhook secret must have 1 to 256 characters among "
                        "A-Z, a-z, 0-9, _ and -."
                    )
                )

    def _get_telegram_client(self):
        """Return a Telegram API client for this bot.

        :rtype: TelegramClient
        :raises UserError: if the bot has no token
        """
        self.ensure_one()
        # sudo: the token is restricted to administrators, but every bot reply
        # needs it, including those sent while handling a user's command.
        token = self.sudo().bot_token
        if not token:
            raise UserError(
                self.env._("Bot '%(name)s' has no token configured.", name=self.name)
            )
        return TelegramClient(token)

    def _get_webhook_url(self):
        """Return the public URL Telegram must post this bot's updates to.

        :rtype: str
        """
        self.ensure_one()
        return f"{self.get_base_url()}/telegram/webhook/{self.sudo().bot_token}"

    def action_register_webhook(self):
        """Register this bot's webhook in Telegram, generating the secret if empty.

        :return: a notification action
        :rtype: dict
        :raises UserError: if Telegram rejects the registration
        """
        self.ensure_one()
        bot = self.sudo()
        if not bot.webhook_secret:
            bot.webhook_secret = secrets.token_urlsafe(32)
        client = bot._get_telegram_client()
        response = client.set_webhook(
            bot._get_webhook_url(), bot.webhook_secret, _ALLOWED_UPDATES
        )
        if not response.get("ok"):
            raise UserError(
                self.env._(
                    "Telegram rejected the webhook: %(error)s",
                    error=response.get("description", "unknown error"),
                )
            )
        _logger.info("Webhook registered for bot '%s'", self.name)
        return {
            "type": "ir.actions.client",
            "tag": "display_notification",
            "params": {
                "title": self.env._("Webhook registered"),
                "message": self.env._("Telegram will send this bot's updates to Odoo."),
                "type": "success",
            },
        }

    def _track_outbound_message(
        self, chat_id, media_type="text", text=None, caption=None
    ):
        """Create a ``telegram.message`` tracking record for an outbound message.

        :param str chat_id: Telegram chat ID
        :param str media_type: media type (text, photo, video, audio, voice, document)
        :param str text: message text, for text messages
        :param str caption: optional caption, for media messages
        :return: the created ``telegram.message`` record
        """
        self.ensure_one()
        chat = (
            self.env["telegram.chat"]
            .sudo()
            .search([("chat_id", "=", str(chat_id)), ("bot_id", "=", self.id)], limit=1)
        )
        vals = {
            "bot_id": self.id,
            "chat_id": chat.id,
            "message_type": "outbound",
            "media_type": media_type,
            "state": "outgoing",
        }
        if text:
            vals["text"] = text
        if caption:
            vals["caption"] = caption
        return self.env["telegram.message"].sudo().create(vals)

    def get_file_content(self, file_id):
        """Download the content of a file given its Telegram file ID.

        :param str file_id: Telegram file ID
        :return: file content on success, ``False`` otherwise
        :rtype: bytes | bool
        """
        self.ensure_one()
        try:
            return self._get_telegram_client().get_file_content(file_id)
        except Exception as e:  # noqa: BLE001 — callers handle a missing file
            _logger.error("Failed to download file for bot '%s': %s", self.name, e)
            return False

    def get_markdown_helpers(self):
        """Return Telegram Markdown formatting helpers for consistent styling.

        :return: mapping of Markdown formatting functions and strings
        :rtype: dict
        """
        return {
            "bold": lambda t: f"*{t}*",
            "italic": lambda t: f"_{t}_",
            "code": lambda t: f"`{t}`",
            "pre": lambda t: f"```\n{t}\n```",
            "link": lambda text, url: f"[{text}]({url})",
            "newline": "\n",
        }

    def _send_tracked(
        self,
        chat_id,
        media_type,
        client_method,
        *args,
        text=None,
        caption=None,
        **kwargs,
    ):
        """Send through ``client_method`` and record the outcome on a tracking message.

        :param str chat_id: Telegram chat ID
        :param str media_type: media type of the tracking record
        :param str client_method: ``TelegramClient`` method to call
        :param args: positional arguments after ``chat_id`` for the client method
        :param str text: text stored on the tracking record
        :param str caption: caption stored on the tracking record
        :param kwargs: keyword arguments for the client method
        :return: response JSON, or ``False`` if the call failed
        """
        self.ensure_one()
        telegram_message = self._track_outbound_message(
            chat_id, media_type, text=text, caption=caption
        )
        try:
            client = self._get_telegram_client()
            response = getattr(client, client_method)(chat_id, *args, **kwargs)
        except Exception as e:
            telegram_message.write({"state": "error", "error_message": str(e)[:255]})
            _logger.exception("Telegram %s to chat %s failed", client_method, chat_id)
            return False
        if response and response.get("ok"):
            telegram_message.write(
                {
                    "state": "sent",
                    "msg_uid": str(response.get("result", {}).get("message_id")),
                }
            )
        else:
            error = (response or {}).get("description", "Unknown error")
            telegram_message.write({"state": "error", "error_message": error[:255]})
        return response

    def send_document(self, chat_id, document_content, filename, caption=None):
        """Send a document to a chat through the Telegram Bot API.

        :param str chat_id: Telegram chat ID
        :param bytes document_content: binary content of the document
        :param str filename: name of the file
        :param str caption: optional caption for the document
        :return: response JSON on success, ``False`` otherwise
        """
        return self._send_tracked(
            chat_id,
            "document",
            "send_document",
            document_content,
            filename,
            caption,
            caption=caption,
        )

    def send_message(self, chat_id, text, reply_markup=None, parse_mode="Markdown"):
        """Send a text message to a chat through the Telegram Bot API.

        :param str chat_id: Telegram chat ID
        :param str text: message text, parsed according to ``parse_mode``
        :param dict reply_markup: optional keyboard markup
        :param str parse_mode: 'Markdown', 'HTML', or None for plain text
        :return: response JSON on success, ``False`` otherwise
        """
        return self._send_tracked(
            chat_id,
            "text",
            "send_message",
            text,
            text=text,
            parse_mode=parse_mode,
            reply_markup=reply_markup,
        )

    def answer_callback_query(self, callback_query_id, text=None, show_alert=False):
        """Answer a callback query, clearing the loading indicator on the button.

        :param str callback_query_id: unique identifier of the query to answer
        :param str text: optional text to show the user (0-200 characters)
        :param bool show_alert: if True, show an alert instead of a notification
        :return: response JSON on success, ``False`` otherwise
        """
        self.ensure_one()
        try:
            return self._get_telegram_client().answer_callback_query(
                callback_query_id, text=text, show_alert=show_alert
            )
        except Exception:
            _logger.exception("Failed to answer callback query %s", callback_query_id)
            return False

    def edit_message_reply_markup(self, chat_id, message_id, reply_markup=None):
        """Replace an existing message's inline keyboard in place.

        :param str chat_id: Telegram chat ID
        :param int message_id: ID of the message whose keyboard is replaced
        :param dict reply_markup: new inline keyboard markup, or None to remove it
        :return: response JSON on success, ``False`` otherwise
        """
        self.ensure_one()
        try:
            return self._get_telegram_client().edit_message_reply_markup(
                chat_id, message_id, reply_markup=reply_markup
            )
        except Exception:
            _logger.exception(
                "Failed to edit message reply markup for chat %s", chat_id
            )
            return False
